package com.saferoute.ai.service;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.concurrent.CompletableFuture;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import com.saferoute.ai.client.OsrmClient;
import com.saferoute.ai.client.RouteCandidate;
import com.saferoute.ai.config.SafeRouteProperties;
import com.saferoute.ai.exception.ExternalServiceException;
import com.saferoute.ai.exception.LocationNotFoundException;
import com.saferoute.ai.geo.GeoPoint;
import com.saferoute.ai.geo.GeoUtils;
import com.saferoute.ai.geo.Polyline;
import com.saferoute.ai.model.TravelMode;

/**
 * Finds candidate routes for a trip.
 * <p>
 * Routing servers often return only one route. To give the user a real choice, "safe detours" are
 * generated by routing through points to either side of the direct line. A detour is kept only if it
 * is not much longer than the shortest route and genuinely different from the routes already found.
 */
@Service
public class RoutingService {

    private static final Logger log = LoggerFactory.getLogger(RoutingService.class);

    static final double MAX_DETOUR_RATIO = 1.6;
    static final double MAX_OVERLAP = 0.75;
    private static final double ROAD_DETOUR_FACTOR = 1.3;
    private static final double WALK_KMH = 4.8;
    private static final double DRIVE_KMH = 22;

    private final OsrmClient osrmClient;
    private final SafeRouteProperties properties;

    public RoutingService(OsrmClient osrmClient, SafeRouteProperties properties) {
        this.osrmClient = osrmClient;
        this.properties = properties;
    }

    /** @param estimated true when no routing server was reachable and a straight line was returned */
    public record RoutingResult(List<RouteCandidate> candidates, boolean estimated) {
    }

    public RoutingResult findRoutes(GeoPoint from, GeoPoint to, TravelMode mode) {
        List<String> servers = mode == TravelMode.WALK
                ? List.of(properties.routing().walkUrl())
                : List.of(properties.routing().driveUrl(), properties.routing().driveFallbackUrl());

        List<RouteCandidate> found = null;
        String usedServer = null;
        for (String server : servers) {
            try {
                found = new ArrayList<>(osrmClient.route(server, List.of(from, to), true));
                usedServer = server;
                break;
            } catch (ExternalServiceException ex) {
                log.warn("Routing server {} failed: {}", server, ex.getMessage());
            }
        }
        if (found == null) {
            return new RoutingResult(List.of(straightLine(from, to, mode)), true);
        }
        if (found.isEmpty()) {
            throw new LocationNotFoundException("No road route connects these two places. Try points closer to a road.");
        }

        int maxRoutes = properties.routing().maxRoutes();
        if (found.size() < maxRoutes) {
            addDetours(found, from, to, usedServer, maxRoutes);
        }
        found.sort(Comparator.comparingDouble(RouteCandidate::durationSeconds));
        return new RoutingResult(found.size() > maxRoutes ? found.subList(0, maxRoutes) : found, false);
    }

    private void addDetours(List<RouteCandidate> found, GeoPoint from, GeoPoint to, String server, int maxRoutes) {
        double shortest = found.stream().mapToDouble(RouteCandidate::distanceMeters).min().orElse(0);
        List<CompletableFuture<List<RouteCandidate>>> requests = new ArrayList<>();
        for (GeoPoint via : detourPoints(from, to)) {
            requests.add(CompletableFuture.supplyAsync(() -> {
                try {
                    return osrmClient.route(server, List.of(from, via, to), false);
                } catch (ExternalServiceException ex) {
                    return List.of();
                }
            }));
        }
        for (CompletableFuture<List<RouteCandidate>> request : requests) {
            if (found.size() >= maxRoutes) {
                break;
            }
            for (RouteCandidate detour : request.join()) {
                if (detour.distanceMeters() <= shortest * MAX_DETOUR_RATIO && isDistinct(detour, found)) {
                    found.add(detour);
                }
            }
        }
    }

    /** Two points either side of the direct line, about 22% of the trip length away from its midpoint. */
    static List<GeoPoint> detourPoints(GeoPoint from, GeoPoint to) {
        double meters = GeoUtils.distanceMeters(from, to);
        double offset = Math.max(250, Math.min(2500, meters * 0.22));
        double midLat = (from.lat() + to.lat()) / 2;
        double midLon = (from.lon() + to.lon()) / 2;
        double metersPerDegLat = 111_320;
        double metersPerDegLon = 111_320 * Math.cos(Math.toRadians(midLat));
        // direction of travel in metres, rotated 90 degrees
        double dx = (to.lon() - from.lon()) * metersPerDegLon;
        double dy = (to.lat() - from.lat()) * metersPerDegLat;
        double length = Math.hypot(dx, dy);
        if (length == 0) {
            return List.of();
        }
        double px = -dy / length;
        double py = dx / length;
        List<GeoPoint> points = new ArrayList<>();
        for (int side : new int[] {1, -1}) {
            points.add(new GeoPoint(midLat + side * py * offset / metersPerDegLat,
                    midLon + side * px * offset / metersPerDegLon));
        }
        return points;
    }

    private static boolean isDistinct(RouteCandidate candidate, List<RouteCandidate> existing) {
        Polyline line = new Polyline(candidate.geometry());
        return existing.stream().allMatch(other ->
                line.overlapWith(new Polyline(other.geometry()), 35) < MAX_OVERLAP);
    }

    private static RouteCandidate straightLine(GeoPoint from, GeoPoint to, TravelMode mode) {
        double meters = GeoUtils.distanceMeters(from, to) * ROAD_DETOUR_FACTOR;
        double kmh = mode == TravelMode.WALK ? WALK_KMH : DRIVE_KMH;
        return new RouteCandidate(meters, meters / 1000.0 / kmh * 3600.0, GeoUtils.interpolate(from, to, 20));
    }
}
